import type { SearchItem, SearchKind } from "./types";

export const SEARCH_KINDS: readonly SearchKind[] = [
  "lesson",
  "exercise",
  "glossary",
  "interview",
  "exam",
  "portfolio",
];

export type SearchFilter = "all" | SearchKind;

export const DEEPLINK_EVENT = "pyai:deeplink";

const KIND_PRIORITY: Record<SearchKind, number> = {
  lesson: 0,
  exercise: 1,
  exam: 2,
  glossary: 3,
  interview: 4,
  portfolio: 5,
};

/**
 * Normalize text for bilingual EN/VI search:
 * NFD decomposition, strip combining diacritics, map đ/Đ -> d, lowercase, collapse spaces.
 */
export function normalizeSearchText(input: string): string {
  return input
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/gi, "d")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .trim();
}

let cachedSearchIndex: Promise<SearchItem[]> | null = null;

/**
 * Lazy-load and memoize the static search index generated by tools/build_content.py.
 */
export function loadSearchIndex(): Promise<SearchItem[]> {
  if (!cachedSearchIndex) {
    cachedSearchIndex = import("@/generated/search.json")
      .then((mod) => {
        const typed = mod as {
          default?: { items?: SearchItem[] };
          items?: SearchItem[];
        };
        return typed.items ?? typed.default?.items ?? [];
      })
      .catch((err) => {
        cachedSearchIndex = null;
        throw err;
      });
  }
  return cachedSearchIndex;
}

function scoreItem(
  item: SearchItem,
  normalizedQuery: string,
  tokens: readonly string[],
): number | null {
  const titleEn = normalizeSearchText(item.title.en);
  const titleVi = item.title.vi ? normalizeSearchText(item.title.vi) : "";
  const subtitleEn = item.subtitle?.en ? normalizeSearchText(item.subtitle.en) : "";
  const subtitleVi = item.subtitle?.vi ? normalizeSearchText(item.subtitle.vi) : "";
  const tagsText = normalizeSearchText(item.tags.join(" "));
  const phaseText = item.phase ? normalizeSearchText(item.phase) : "";

  let score = 0;

  for (const token of tokens) {
    const inTitle = titleEn.includes(token) || titleVi.includes(token);
    const inMeta = tagsText.includes(token) || phaseText.includes(token);
    const inSubtitle = subtitleEn.includes(token) || subtitleVi.includes(token);

    if (!inTitle && !inMeta && !inSubtitle) {
      return null;
    }

    if (inTitle) score += 20;
    if (inMeta) score += 12;
    if (inSubtitle) score += 6;
  }

  if (
    titleEn === normalizedQuery ||
    (titleVi !== "" && titleVi === normalizedQuery)
  ) {
    score += 100;
  }
  if (
    titleEn.startsWith(normalizedQuery) ||
    (titleVi !== "" && titleVi.startsWith(normalizedQuery))
  ) {
    score += 60;
  }
  if (
    titleEn.includes(normalizedQuery) ||
    (titleVi !== "" && titleVi.includes(normalizedQuery))
  ) {
    score += 35;
  }

  return score;
}

/**
 * Filter and rank search items across EN/VI titles, subtitles, tags, and phase.
 */
export function searchItems(
  items: readonly SearchItem[],
  query: string,
  filter: SearchFilter = "all",
  limit = 30,
): SearchItem[] {
  const normalizedQuery = normalizeSearchText(query);
  if (!normalizedQuery) return [];

  const tokens = normalizedQuery.split(" ");
  const candidates =
    filter === "all" ? items : items.filter((item) => item.kind === filter);

  const scored: { item: SearchItem; score: number }[] = [];
  for (const item of candidates) {
    const score = scoreItem(item, normalizedQuery, tokens);
    if (score !== null) {
      scored.push({ item, score });
    }
  }

  scored.sort((a, b) => {
    if (b.score !== a.score) return b.score - a.score;
    const kindDiff = KIND_PRIORITY[a.item.kind] - KIND_PRIORITY[b.item.kind];
    if (kindDiff !== 0) return kindDiff;
    return a.item.title.en.localeCompare(b.item.title.en);
  });

  return scored.slice(0, limit).map((entry) => entry.item);
}
